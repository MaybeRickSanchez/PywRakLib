"""
Byte-for-byte wire-format tests.

The expected hex strings were generated by running the original PHP implementation
(https://github.com/pmmp/RakLib) against identical inputs, so these tests guarantee that this Python port produces
exactly the same bytes on the wire.
"""

import unittest

from raklib.protocol.ACK import ACK
from raklib.protocol.ConnectedPing import ConnectedPing
from raklib.protocol.ConnectedPong import ConnectedPong
from raklib.protocol.ConnectionRequest import ConnectionRequest
from raklib.protocol.ConnectionRequestAccepted import ConnectionRequestAccepted
from raklib.protocol.Datagram import Datagram
from raklib.protocol.EncapsulatedPacket import EncapsulatedPacket
from raklib.protocol.IncompatibleProtocolVersion import IncompatibleProtocolVersion
from raklib.protocol.NACK import NACK
from raklib.protocol.NewIncomingConnection import NewIncomingConnection
from raklib.protocol.OpenConnectionReply1 import OpenConnectionReply1
from raklib.protocol.OpenConnectionReply2 import OpenConnectionReply2
from raklib.protocol.OpenConnectionRequest2 import OpenConnectionRequest2
from raklib.protocol.PacketReliability import PacketReliability
from raklib.protocol.PacketSerializer import PacketSerializer
from raklib.protocol.SplitPacketInfo import SplitPacketInfo
from raklib.protocol.UnconnectedPing import UnconnectedPing
from raklib.protocol.UnconnectedPingOpenConnections import UnconnectedPingOpenConnections
from raklib.protocol.UnconnectedPong import UnconnectedPong
from raklib.utils.InternetAddress import InternetAddress

V4 = InternetAddress("127.0.0.1", 19132, 4)
V6 = InternetAddress("2001:db8::1", 19132, 6)


def hexOf(packet) -> str:
    s = PacketSerializer()
    packet.encode(s)
    return s.getBuffer().hex()


class WireVectorsTest(unittest.TestCase):
    def test_unconnected_ping(self):
        p = UnconnectedPing()
        p.sendPingTime = 123456789
        p.clientId = 42
        self.assertEqual(
            "0100000000075bcd1500ffff00fefefefefdfdfdfd12345678000000000000002a",
            hexOf(p),
        )

    def test_unconnected_ping_open_connections(self):
        p = UnconnectedPingOpenConnections()
        p.sendPingTime = 5
        p.clientId = -1
        self.assertEqual(
            "02000000000000000500ffff00fefefefefdfdfdfd12345678ffffffffffffffff",
            hexOf(p),
        )

    def test_unconnected_pong(self):
        p = UnconnectedPong.create(99, 0x1122334455667788, b"MCPE;A Minecraft Server;")
        self.assertEqual(
            "1c0000000000000063112233445566778800ffff00fefefefefdfdfdfd12345678"
            "00184d4350453b41204d696e656372616674205365727665723b",
            hexOf(p),
        )

    def test_open_connection_reply1_no_cookie(self):
        p = OpenConnectionReply1.create(0x1122334455667788, None, 1400)
        self.assertEqual(
            "0600ffff00fefefefefdfdfdfd123456781122334455667788000578", hexOf(p)
        )

    def test_open_connection_reply1_cookie(self):
        p = OpenConnectionReply1.create(0x1122334455667788, 0xCAFEBABE, 1400)
        self.assertEqual(
            "0600ffff00fefefefefdfdfdfd12345678112233445566778801cafebabe0578", hexOf(p)
        )

    def test_open_connection_request2_no_cookie(self):
        p = OpenConnectionRequest2()
        p.clientID = 12345
        p.serverAddress = V4
        p.mtuSize = 1400
        self.assertEqual(
            "0700ffff00fefefefefdfdfdfd123456780480fffffe4abc05780000000000003039", hexOf(p)
        )

    def test_open_connection_request2_cookie(self):
        p = OpenConnectionRequest2()
        p.clientID = 12345
        p.serverAddress = V4
        p.mtuSize = 1400
        p.cookie = 0xDEADBEEF
        self.assertEqual(
            "0700ffff00fefefefefdfdfdfd12345678deadbeef000480fffffe4abc05780000000000003039",
            hexOf(p),
        )

    def test_open_connection_reply2_v4(self):
        p = OpenConnectionReply2.create(0x1122334455667788, V4, 1400, False)
        self.assertEqual(
            "0800ffff00fefefefefdfdfdfd1234567811223344556677880480fffffe4abc057800", hexOf(p)
        )

    def test_open_connection_reply2_v6(self):
        p = OpenConnectionReply2.create(0x1122334455667788, V6, 1400, True)
        self.assertEqual(
            "0800ffff00fefefefefdfdfdfd123456781122334455667788060a004abc0000000020010db8"
            "00000000000000000000000100000000057801",
            hexOf(p),
        )

    def test_incompatible_protocol_version(self):
        p = IncompatibleProtocolVersion.create(10, 0x123456789ABCDEF0)
        self.assertEqual(
            "190a00ffff00fefefefefdfdfdfd12345678123456789abcdef0", hexOf(p)
        )

    def test_connection_request(self):
        p = ConnectionRequest()
        p.clientID = 777
        p.sendPingTime = 888
        p.useSecurity = False
        self.assertEqual("090000000000000309000000000000037800", hexOf(p))

    def test_connection_request_accepted(self):
        p = ConnectionRequestAccepted.create(V4, [], 111, 222)
        expected = (
            "100480fffffe4abc0000"
            + "04ffffffff0000" * 20
            + "000000000000006f00000000000000de"
        )
        self.assertEqual(expected, hexOf(p))

    def test_new_incoming_connection(self):
        p = NewIncomingConnection()
        p.address = V4
        p.systemAddresses = [V4, InternetAddress("10.0.0.1", 1, 4)]
        p.sendPingTime = 5
        p.sendPongTime = 6
        self.assertEqual(
            "130480fffffe4abc0480fffffe4abc04f5fffffe000100000000000000050000000000000006",
            hexOf(p),
        )

    def test_connected_ping_pong(self):
        self.assertEqual("00000000000000022b", hexOf(ConnectedPing.create(555)))
        self.assertEqual(
            "03000000000000022b000000000000029a", hexOf(ConnectedPong.create(555, 666))
        )

    def test_ack(self):
        p = ACK()
        p.packets = [1, 2, 3, 5, 7, 8, 9, 10]
        self.assertEqual("c000030001000003000001050000000700000a0000", hexOf(p))

    def test_nack(self):
        p = NACK()
        p.packets = [4]
        self.assertEqual("a0000101040000", hexOf(p))

    def test_encapsulated_ordered(self):
        p = EncapsulatedPacket()
        p.reliability = PacketReliability.RELIABLE_ORDERED
        p.messageIndex = 5
        p.orderIndex = 7
        p.orderChannel = 0
        p.buffer = b"hello world"
        self.assertEqual("6000580500000700000068656c6c6f20776f726c64", p.toBinary().hex())

    def test_encapsulated_unreliable(self):
        p = EncapsulatedPacket()
        p.reliability = PacketReliability.UNRELIABLE
        p.buffer = b"abc"
        self.assertEqual("000018616263", p.toBinary().hex())

    def test_encapsulated_split(self):
        p = EncapsulatedPacket()
        p.reliability = PacketReliability.RELIABLE
        p.messageIndex = 1
        p.splitInfo = SplitPacketInfo(0x1234, 1, 3)
        p.buffer = b"frag"
        self.assertEqual("5000200100000000000312340000000166726167", p.toBinary().hex())

    def test_datagram(self):
        d = Datagram()
        d.seqNumber = 100
        e = EncapsulatedPacket()
        e.reliability = PacketReliability.UNRELIABLE
        e.buffer = b"x"
        d.packets = [e]
        self.assertEqual("8064000000000878", hexOf(d))


class DecodeVectorsTest(unittest.TestCase):
    def test_decode_open_connection_request2_cookie(self):
        p = OpenConnectionRequest2()
        p.clientID = 12345
        p.serverAddress = V4
        p.mtuSize = 1400
        p.cookie = 0xCAFEBABE
        decoded = OpenConnectionRequest2()
        decoded.decode(PacketSerializer(bytes.fromhex(hexOf(p))))
        self.assertEqual(0xCAFEBABE, decoded.cookie)
        self.assertEqual(12345, decoded.clientID)
        self.assertEqual(1400, decoded.mtuSize)
        self.assertEqual("127.0.0.1 19132", decoded.serverAddress.toString())

    def test_decode_new_incoming_connection(self):
        p = NewIncomingConnection()
        p.address = V4
        p.systemAddresses = [V4]
        p.sendPingTime = 5
        p.sendPongTime = 6
        decoded = NewIncomingConnection()
        decoded.decode(PacketSerializer(bytes.fromhex(hexOf(p))))
        self.assertEqual("127.0.0.1 19132", decoded.address.toString())
        self.assertEqual(5, decoded.sendPingTime)
        self.assertEqual(6, decoded.sendPongTime)

    def test_decode_ack(self):
        p = ACK()
        p.packets = [1, 2, 3, 5, 7, 8, 9, 10]
        decoded = ACK()
        decoded.decode(PacketSerializer(bytes.fromhex(hexOf(p))))
        self.assertEqual([1, 2, 3, 5, 7, 8, 9, 10], decoded.packets)


if __name__ == "__main__":
    unittest.main()